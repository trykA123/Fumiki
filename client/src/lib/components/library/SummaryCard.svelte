<script lang="ts">
    import { api } from "$lib/api/client";
    import Icon from "$lib/components/Icon.svelte";
    import { fade } from "svelte/transition";
    import { toast } from "$lib/stores/toast";

    let { bookId }: { bookId: string } = $props();

    type PromptType = "character" | "plot" | "thematic";
    type SummaryState = {
        content: string;
        cached: boolean;
        provider: string;
    } | null;

    let activeTab = $state<PromptType>("plot");
    let loading = $state(false);
    let summaryData = $state<Record<PromptType, SummaryState>>({
        plot: null,
        character: null,
        thematic: null,
    });

    const tabs: { id: PromptType; label: string }[] = [
        { id: "plot", label: "Plot Summary" },
        { id: "character", label: "Characters" },
        { id: "thematic", label: "Themes" },
    ];

    async function loadSummary(type: PromptType, forceRefresh = false) {
        if (!bookId) return;

        // Return early if already loaded and not forcing a refresh
        if (summaryData[type] && !forceRefresh) return;

        loading = true;
        try {
            const data: any = await api.post("/summaries/generate", {
                bookId,
                promptType: type,
                forceRefresh,
            });
            summaryData[type] = {
                content: data.content,
                cached: data.cached,
                provider: data.provider,
            };
        } catch (e: any) {
            toast.add(e.message || "Failed to load summary", "error");
        } finally {
            loading = false;
        }
    }

    function switchTab(tab: PromptType) {
        activeTab = tab;
        loadSummary(tab);
    }
</script>

<div
    class="w-full bg-surface-1 rounded-[16px] border border-border-subtle overflow-hidden flex flex-col mt-4"
>
    <!-- Header / Tabs -->
    <div
        class="flex items-center justify-between border-b border-border-subtle bg-surface-1 px-2 pt-2 pb-0"
    >
        <div class="flex gap-4 px-2">
            {#each tabs as tab}
                <button
                    class={`pb-2 font-medium text-sm border-b-2 transition-all cursor-pointer ${
                        activeTab === tab.id
                            ? "border-accent text-text-primary"
                            : "border-transparent text-text-muted hover:text-text-primary"
                    }`}
                    onclick={() => switchTab(tab.id)}
                >
                    {tab.label}
                </button>
            {/each}
        </div>

        <div class="px-2 pb-2">
            {#if !loading && summaryData[activeTab]}
                <button
                    class="text-xs text-text-muted hover:text-accent flex items-center gap-1 cursor-pointer transition-colors"
                    onclick={() => loadSummary(activeTab, true)}
                    title="Regenerate with AI"
                >
                    <Icon name="play" size={12} />
                    Regenerate
                </button>
            {/if}
        </div>
    </div>

    <!-- Content -->
    <div class="p-6 min-h-[160px] relative bg-surface-0">
        {#if loading}
            <div
                class="absolute inset-0 flex flex-col items-center justify-center bg-surface-0/80 backdrop-blur-sm z-10"
                in:fade
            >
                <div
                    class="w-6 h-6 border-2 border-surface-2 border-t-accent rounded-full animate-spin mb-3"
                ></div>
                <span class="text-sm font-medium text-text-muted animate-pulse"
                    >Consulting AI...</span
                >
            </div>
        {/if}

        <div class="text-text-primary leading-[1.6] text-[15px] max-w-none">
            {#if summaryData[activeTab]}
                <div
                    in:fade={{ duration: 200 }}
                    class="flex flex-col gap-4 whitespace-pre-wrap"
                >
                    {summaryData[activeTab]?.content}

                    <div
                        class="mt-4 pt-4 border-t border-border-subtle flex items-center justify-between text-xs text-text-muted"
                    >
                        <span
                            >Generated by {summaryData[
                                activeTab
                            ]?.provider.toUpperCase()}</span
                        >
                        {#if summaryData[activeTab]?.cached}
                            <span class="flex items-center gap-1"
                                ><Icon name="edit" size={12} /> Loaded from cache</span
                            >
                        {/if}
                    </div>
                </div>
            {:else if !loading}
                <div
                    class="h-full flex flex-col items-center justify-center text-center text-text-muted py-6"
                >
                    <Icon name="search" size={24} class="mb-3 opacity-50" />
                    <p class="mb-4 text-sm">No analysis loaded yet.</p>
                    <button
                        class="bg-accent text-surface-0 hover:brightness-110 px-4 py-2 rounded-[6px] text-sm font-medium cursor-pointer transition-all"
                        onclick={() => loadSummary(activeTab)}
                    >
                        Generate Analysis
                    </button>
                </div>
            {/if}
        </div>
    </div>
</div>
